"""Bail class and maximum punishment of a section from the official First Schedule tables.

`configs/first_schedule_crpc_ipc.jsonl` (CrPC 1973, First Schedule Part I: IPC offences) and
`configs/first_schedule_bnss_bns.jsonl` (BNSS 2023, First Schedule: BNS offences) are generated by
`scripts/extract_gap_statutes.py` from the official PDFs (source URL and SHA-256 in each row and in the `.meta.json`
beside it); a cell the script could not read safely is null. Peshkar reads them after the statute store, and a non-null
value here wins: the statute store built on 26 Oct carries the bail flag the wrong way round for 43 IPC sections
(`docs/handoff/first-schedule.md`), and until the store is rebuilt the schedule is the better source. A BNS entry such as
"318(4)" is a sub-row of section 318, so a section with a sub-section is looked up in that row's `subrows`.
"""

from __future__ import annotations

import json
import re
from functools import lru_cache
from pathlib import Path

from vakeel_sahayak.config import resolve_config_dir

FILES = {"IPC": "first_schedule_crpc_ipc.jsonl", "BNS": "first_schedule_bnss_bns.jsonl"}
_REF = re.compile(r"^\s*(\d+[A-Z]*)\s*(\(.*)?$")


@lru_cache(maxsize=8)
def _table(code: str, config_dir: str) -> dict[str, dict]:
    path = Path(config_dir) / FILES[code]
    if not path.is_file():
        return {}
    rows: dict[str, dict] = {}
    with path.open(encoding="utf-8") as fh:
        for line in fh:
            if line.strip():
                row = json.loads(line)
                if row.get("section"):
                    rows[str(row["section"])] = row
    return rows


def _punishment(text: str | None) -> str | None:
    """The statute store's wording: 'life' for life imprisonment (the store and the brief already read 'life' and 'death')."""
    if not text:
        return None
    return "life" if text.strip().lower() == "life imprisonment" else text.strip()


def classify(code: str, section: str, config_dir: str | None = None) -> tuple[bool | None, str | None]:
    """(bailable, maximum punishment) of one section from the First Schedule, None where the schedule does not say.

    Args:
        code: 'IPC' or 'BNS' (any other code: nothing)
        section: '302', '498A', '318(4)'
        config_dir: the configs directory (default: `resolve_config_dir()`)
    """
    if code not in FILES:
        return None, None
    m = _REF.match(section or "")
    if m is None:
        return None, None
    base, sub = m.group(1), (m.group(2) or "").replace(" ", "")
    row = _table(code, str(resolve_config_dir(config_dir))).get(base)
    if row is None:
        return None, None
    if sub:
        for s in row.get("subrows") or []:
            if s.get("subsection") and sub.startswith(str(s["subsection"]).replace(" ", "")):
                return s.get("bailable"), _punishment(s.get("max_punishment"))
    return row.get("bailable"), _punishment(row.get("max_punishment"))
