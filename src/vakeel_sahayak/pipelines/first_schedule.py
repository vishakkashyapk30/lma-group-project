"""Bail class and maximum punishment of a section from the official First Schedule tables.

`configs/first_schedule_crpc_ipc.jsonl` (CrPC 1973, First Schedule Part I: IPC offences) and
`configs/first_schedule_bnss_bns.jsonl` (BNSS 2023, First Schedule: BNS offences) are generated by
`scripts/extract_gap_statutes.py` from the official PDFs (source URL and SHA-256 in each row and in the `.meta.json`
beside it); a cell the script could not read safely is null. Peshkar reads them after the statute store, and a non-null
value here wins: the statute store built on 26 Oct carries the bail flag the wrong way round for 43 IPC sections
(`docs/handoff/first-schedule.md`), and until the store is rebuilt the schedule is the better source. A BNS entry such as
"318(4)" is a sub-row of section 318, so a section with a sub-section is looked up in that row's `subrows`.

`configs/first_schedule_part2.jsonl` holds Part II of both schedules (offences against other laws: three bands of maximum
punishment), read by `classify_other_law`; Peshkar uses it last, only for a section of another law that still has no bail class.
"""

from __future__ import annotations

import json
import re
from functools import lru_cache
from pathlib import Path

from vakeel_sahayak.config import resolve_config_dir

FILES = {"IPC": "first_schedule_crpc_ipc.jsonl", "BNS": "first_schedule_bnss_bns.jsonl"}
_REF = re.compile(r"^\s*(\d+[A-Z]*)\s*(\(.*)?$")


@lru_cache(maxsize=8)
def _table(code: str, config_dir: str) -> dict[str, dict]:
    path = Path(config_dir) / FILES[code]
    if not path.is_file():
        return {}
    rows: dict[str, dict] = {}
    with path.open(encoding="utf-8") as fh:
        for line in fh:
            if line.strip():
                row = json.loads(line)
                if row.get("section"):
                    rows[str(row["section"])] = row
    return rows


def _punishment(text: str | None) -> str | None:
    """The statute store's wording: 'life' for life imprisonment (the store and the brief already read 'life' and 'death')."""
    if not text:
        return None
    return "life" if text.strip().lower() == "life imprisonment" else text.strip()


def classify(code: str, section: str, config_dir: str | None = None) -> tuple[bool | None, str | None]:
    """(bailable, maximum punishment) of one section from the First Schedule, None where the schedule does not say.

    Args:
        code: 'IPC' or 'BNS' (any other code: nothing)
        section: '302', '498A', '318(4)'
        config_dir: the configs directory (default: `resolve_config_dir()`)
    """
    if code not in FILES:
        return None, None
    m = _REF.match(section or "")
    if m is None:
        return None, None
    base, sub = m.group(1), (m.group(2) or "").replace(" ", "")
    row = _table(code, str(resolve_config_dir(config_dir))).get(base)
    if row is None:
        return None, None
    if sub:
        for s in row.get("subrows") or []:
            if s.get("subsection") and sub.startswith(str(s["subsection"]).replace(" ", "")):
                return s.get("bailable"), _punishment(s.get("max_punishment"))
    return row.get("bailable"), _punishment(row.get("max_punishment"))


# Provisions that make a person liable for another's offence and set no punishment of their own: the charge carries the punishment of
# the offence they attach to. IPC s.34 and its BNS counterpart s.3(5) (common intention) are in no schedule row at all.
COMMON_INTENTION = frozenset({("IPC", "34"), ("BNS", "3(5)")})
_SAME_AS_OFFENCE = re.compile(r"^\s*the\s+same\s+as\s+for\s+the\s+offence\b", re.I)


def carries_offence_punishment(code: str, section: str, config_dir: str | None = None) -> bool:
    """True when a charged IPC/BNS section has no punishment of its own: it carries that of the offence charged with it.

    Two sources: the section is IPC 34 / BNS 3(5) (common intention), or its First Schedule row prints its punishment as
    "The same as for the offence" (IPC 149, BNS 190: member of an unlawful assembly). A section whose punishment is relative in another way
    (conspiracy, abetment: "same as for abetment of ...") is not one of these and stays unknown.
    """
    key = (code.upper(), "".join((section or "").split()).upper())
    if key in COMMON_INTENTION:
        return True
    if code not in FILES:
        return False
    m = _REF.match(section or "")
    row = _table(code, str(resolve_config_dir(config_dir))).get(m.group(1)) if m else None
    return bool(row and _SAME_AS_OFFENCE.match(str(row.get("punishment") or "")))


_NUMBER_WORDS = {"one": 1, "two": 2, "three": 3, "four": 4, "five": 5, "six": 6, "seven": 7, "eight": 8, "nine": 9, "ten": 10,
                 "fifteen": 15, "twenty": 20}  # fmt: skip


def ndps_is_quantity_dependent(text: str | None) -> bool:
    """True when an NDPS section's text sets its punishment by quantity bands (a small and a commercial quantity are both named)."""
    low = (text or "").lower()
    return "small quantity" in low and "commercial quantity" in low


def ndps_clause_maximum(section: str, text: str | None) -> str | None:
    """The maximum term of the quantity clause a charged NDPS section names, read from the section's own text; None otherwise.

    `section` is as the dossier writes it ('21(a)', '20(b)(ii)(A)'). The clause is found at the start of a paragraph of `text` and must
    name a quantity ('where the contravention involves small quantity ... may extend to one year'). Only a clause that is a quantity band
    (the same rule the Rights Radar uses, `rights.acts.ChargedSection.ndps_quantity`) resolves; a bare section number, or a clause
    that is not a band, returns None, because the maximum then depends on the quantity.

    Returns:
        '1 year', '10 years', '20 years' (the term the clause says it may extend to), or None.
    """
    from vakeel_sahayak.rights.acts import parse_section

    charged = parse_section(f"NDPS {section}")
    if charged.ndps_quantity is None:
        return None
    label = re.findall(r"\(([^)]*)\)", charged.clause)[-1]
    for para in (text or "").splitlines():
        para = para.strip()
        if not para.startswith(f"({label})") or "quantity" not in para.lower():
            continue
        m = re.search(r"may\s+extend\s+to\s+([a-z0-9]+)\s+(year|month)s?", para, re.I)
        if not m:
            return None
        num = m.group(1).lower()
        value = int(num) if num.isdigit() else _NUMBER_WORDS.get(num)
        return f"{value} {m.group(2).lower()}{'s' if value != 1 else ''}" if value else None
    return None


# ---- Part II: offences against other laws

PART2_FILE = "first_schedule_part2.jsonl"
PART2_SCHEDULE = "BNSS 2023"  # the CrPC 1973 rows print the same three bands and classes (tests/unit/pipelines/test_first_schedule_lookup.py)
_TERM = re.compile(r"(\d+(?:\.\d+)?)\s*(years?|months?|weeks?|days?|hours?)\b", re.I)
_UNIT_YEARS = {"year": 1.0, "month": 1 / 12, "week": 7 / 365, "day": 1 / 365, "hour": 1 / (365 * 24)}


@lru_cache(maxsize=8)
def part2_rows(config_dir: str, schedule: str = PART2_SCHEDULE) -> tuple[dict, ...]:
    """The rows of one schedule (`schedule` field) in `configs/first_schedule_part2.jsonl`; empty when the file is missing."""
    path = Path(config_dir) / PART2_FILE
    if not path.is_file():
        return ()
    with path.open(encoding="utf-8") as fh:
        rows = [json.loads(line) for line in fh if line.strip()]
    return tuple(r for r in rows if r.get("schedule") == schedule)


def _parse_maximum(text: str | None) -> tuple[str, float | None] | None:
    """('death' | 'life' | 'fine' | 'term', years) of a maximum-punishment string; None when it names none of them."""
    if not text:
        return None
    low = text.strip().lower()
    if re.search(r"\bdeath\b", low):
        return "death", None
    if re.search(r"\blife\b", low):  # 'life', 'life imprisonment', 'imprisonment for life'
        return "life", None
    best = None
    for m in _TERM.finditer(low):
        years = float(m.group(1)) * _UNIT_YEARS[m.group(2).rstrip("s")]
        best = years if best is None else max(best, years)
    if best is not None:
        return "term", best
    if re.fullmatch(r"(with\s+)?fine(\s+only)?\.?", low):
        return "fine", None
    return None


def _in_band(row: dict, kind: str, years: float | None) -> bool:
    if kind == "death":
        return bool(row.get("death"))
    if kind == "life":
        return bool(row.get("life"))
    if kind == "fine":
        return bool(row.get("fine_only"))
    lo, hi = row.get("min_years"), row.get("max_years")
    if years is None or (lo is None and hi is None):
        return False
    above = lo is None or years > lo or (years == lo and bool(row.get("min_inclusive")))
    below = hi is None or years < hi or (years == hi and bool(row.get("max_inclusive")))
    return above and below


def classify_other_law(max_punishment: str | None, config_dir: str | None = None) -> bool | None:
    """Bail class of an offence against a law other than the IPC / BNS, from Part II of the First Schedule (BNSS 2023; CrPC 1973 the same).

    Part II classes such an offence by its maximum punishment: death, life, or more than 7 years: non-bailable; 3 to 7 years:
    non-bailable; less than 3 years or fine only: bailable. It is the fallback where neither the statute store nor the special law gives
    a class (NDPS s.37, for example, names the sections it bars). The bands are read from `configs/first_schedule_part2.jsonl`
    (extracted by `scripts/extract_gap_statutes.py` from the official PDFs), not written here.

    Args:
        max_punishment: 'death', 'life', 'life imprisonment', '20 years', '1 year', '6 months', 'fine', ...
        config_dir: the configs directory (default: `resolve_config_dir()`)

    Returns:
        True (bailable) or False (non-bailable); None when the punishment is missing or not understood, or not exactly one band holds it.
    """
    parsed = _parse_maximum(max_punishment)
    if parsed is None:
        return None
    kind, years = parsed
    hits = [r for r in part2_rows(str(resolve_config_dir(config_dir))) if _in_band(r, kind, years)]
    if len(hits) != 1:
        return None
    return hits[0].get("bailable")
